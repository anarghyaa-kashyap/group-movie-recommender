"""Compare the RL (v1 and v2), DL and QML group recommenders.

Loads the latest registered version of each model from the MLflow Model Registry (so it compares exactly
what was uploaded), evaluates them plus two baselines on the NFR-06 protocol (scripts/simulation.evaluate:
real IMDb catalogue, 30 simulated groups x 8 movie nights, seeds 7, 11 and 23), logs one MLflow run per model
in the "group-recommender-comparison" experiment, and writes docs/model_comparison.json and .md.

Run from the repo root, after the model scripts:
    python -m scripts.rl_model
    python -m scripts.rl_v2_model
    python -m scripts.dl_model
    python -m scripts.qml_model
    python -m scripts.compare_models          # about 5-10 minutes on a laptop CPU
"""
import argparse
import json
import os

import numpy as np

from scripts import simulation as sim_mod
from scripts.rl_model import RLRanker

MODELS = ("rl", "rl_v2", "dl", "qml")
LABELS = {
    "rl": "RL v1 — hybrid + Thompson-sampling bandit (deployed)",
    "rl_v2": "RL v2 — hybrid + adaptive per-group bandit",
    "dl": "DL — PyTorch two-tower network",
    "qml": "QML — 6-qubit variational circuit",
    "preference_only": "Baseline: preferences only",
    "rating_only": "Baseline: public rating only",
}
SHORT = {"rl": "RL v1", "rl_v2": "RL v2", "dl": "DL", "qml": "QML", "preference_only": "pref-only", "rating_only": "rating-only"}
LEARNS = {
    "rl": ("each group's own 1–5 ratings, online", "yes — 22-d bandit, fixed weight 0.05"),
    "rl_v2": ("each group's own 1–5 ratings, online", "yes — 3-d bandit over [C, R, 1], weight grows with ratings"),
    "dl": ("simulated movie nights, offline", "no (fixed after training)"),
    "qml": ("simulated movie nights, offline", "no (fixed after training)"),
}


def load_registered(mlflow, key):
    """Latest registered version of a model -> (ranker, info about it)."""
    name = sim_mod.MODEL_NAMES[key]
    client = mlflow.MlflowClient()
    versions = client.search_model_versions(f"name='{name}'")
    if not versions:
        raise SystemExit(f"{name} is not registered yet: run  python -m scripts.{key}_model  first.")
    v = max(versions, key=lambda m: int(m.version))
    ranker = mlflow.pyfunc.load_model(f"models:/{name}/{v.version}").unwrap_python_model().ranker
    metrics = client.get_run(v.run_id).data.metrics
    return ranker, {
        "registered_model": name,
        "version": int(v.version),
        "run_id": v.run_id,
        "train_seconds": round(metrics.get("train_seconds", 0.0), 1),
        "tuning_seconds": round(metrics.get("tuning_seconds", 0.0), 1),
        **ranker.describe(),
    }


def sanity_example(rankers, feat):
    votes = sim_mod.sanity_votes(feat)
    out = {}
    for key in MODELS:
        ids = rankers[key].rank(votes, top_k=5)
        out[key] = [f"{feat.by_id[m]['title']} ({feat.by_id[m]['vote_average']}, {feat.by_id[m]['vote_count']:,} votes)" for m in ids]
    return out


def learning_gain(r):
    """Mean reward of the later nights minus the earlier nights: > 0 means the model improves as the group rates."""
    rp = r["reward_per_session"]
    half = len(rp) // 2
    return float(np.mean(rp[half:]) - np.mean(rp[:half]))


def offline_cost(i):
    if i["family"] == "RL":
        return f"none (grid search {i['tuning_seconds']:.0f} s)" if i["tuning_seconds"] else "none"
    return f"{i['train_seconds']:.0f} s training"


def write_report(summary, info, sanity, protocol, path):
    rows = sorted(summary.items(), key=lambda kv: -kv[1]["ndcg@10"])
    best_ndcg = rows[0][0]
    best_reward = max(summary, key=lambda k: summary[k]["mean_reward"])
    fastest = min(MODELS, key=lambda k: summary[k]["latency_ms_p95"])
    s = summary
    cols = " | ".join(SHORT[k] for k in MODELS)
    sep = "|---|" + "---|" * len(MODELS)

    def row(label, fn):
        return f"| {label} | " + " | ".join(fn(k) for k in MODELS) + " |"

    L = [
        "# RL vs DL vs QML — Group Movie Recommender",
        "",
        "Generated by `python -m scripts.compare_models` from the models registered in MLflow. Same offline protocol as "
        f"NFR-06 (`scripts/evaluate.py`): real IMDb catalogue ({protocol['catalogue_size']:,} films), "
        f"{protocol['groups']} simulated groups of 3–5 members × {protocol['sessions']} movie nights, "
        f"evaluation seeds {', '.join(map(str, protocol['seeds']))}, averaged. DL and QML were trained on simulated "
        f"movie nights from seed {sim_mod.TRAIN_SEED}; RL v2's settings were grid-searched on seed {sim_mod.TUNING_SEED}. "
        "Both are disjoint from the evaluation seeds.",
        "",
        "## The models",
        "",
        f"| | {cols} |",
        sep,
        row("What it is", lambda k: info[k]["summary"]),
        row("Learns from", lambda k: LEARNS[k][0]),
        row("Adapts to one group's feedback", lambda k: LEARNS[k][1]),
        row("Trainable parameters", lambda k: f"{info[k]['parameters']} per group (online)" if info[k]["family"] == "RL"
            else f"{info[k]['parameters']:,}"),
        row("Offline cost", lambda k: offline_cost(info[k])),
        row("MLflow model", lambda k: f"`{info[k]['registered_model']}` v{info[k]['version']}"),
        "",
        "## Results",
        "",
        "| Model | NDCG@10 ↑ | Precision@10 ↑ | Mean reward (1–5) ↑ | Reward night 1 → 8 | Learning gain ↑ | "
        "Median IMDb votes of top 10 | Latency mean / p95 (ms) |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for k, r in rows:
        rp = r["reward_per_session"]
        L.append(
            f"| {LABELS[k]} | **{r['ndcg@10']:.3f}** | {r['precision@10']:.3f} | {r['mean_reward']:.2f} | "
            f"{rp[0]:.2f} → {rp[-1]:.2f} | {learning_gain(r):+.3f} | {r['median_imdb_votes_top10']:,} | "
            f"{r['latency_ms_mean']:.1f} / {r['latency_ms_p95']:.1f} |"
        )
    L += [
        "",
        "NDCG@10 per evaluation seed: " + "; ".join(f"{SHORT[k]} {s[k]['ndcg@10_per_seed']}" for k in MODELS) + ".",
        "",
        "- **NDCG@10**: how close the top 10 is to the group's ideal order (1 = perfect).",
        "- **Precision@10**: share of the top 10 that is in the group's true top 5 % of the catalogue.",
        "- **Reward**: the simulated group's rounded mean rating of the film it watched (the #1 pick); the RL bandits learn from it.",
        "- **Learning gain**: mean reward of nights 5–8 minus nights 1–4. Above 0 = the model gets better as the group rates films. "
        "(Watched films are excluded afterwards, so the best matches get used up; a flat line is not automatically a failure.)",
        "- **Median IMDb votes**: how mainstream the recommended films are.",
        "",
        "## RL v1 vs RL v2",
        "",
        "| | RL v1 | RL v2 | Change |",
        "|---|---|---|---|",
    ]
    v1, v2 = s["rl"], s["rl_v2"]
    for label, a, b, fmt in [
        ("NDCG@10", v1["ndcg@10"], v2["ndcg@10"], "{:.3f}"),
        ("Precision@10", v1["precision@10"], v2["precision@10"], "{:.3f}"),
        ("Mean reward", v1["mean_reward"], v2["mean_reward"], "{:.2f}"),
        ("Reward, night 1", v1["reward_per_session"][0], v2["reward_per_session"][0], "{:.2f}"),
        ("Reward, night 8", v1["reward_per_session"][-1], v2["reward_per_session"][-1], "{:.2f}"),
        ("Learning gain", learning_gain(v1), learning_gain(v2), "{:+.3f}"),
        ("Latency p95 (ms)", v1["latency_ms_p95"], v2["latency_ms_p95"], "{:.0f}"),
    ]:
        L.append(f"| {label} | {fmt.format(a)} | {fmt.format(b)} | {b - a:+.3f} |")
    L += [
        "",
        "## Reward per movie night",
        "",
        "| Night | " + " | ".join(SHORT[k] for k, _ in rows) + " |",
        "|---|" + "---|" * len(rows),
    ]
    for n in range(protocol["sessions"]):
        L.append(f"| {n + 1} | " + " | ".join(f"{r['reward_per_session'][n]:.2f}" for _, r in rows) + " |")
    L += [
        "",
        "## Sanity check: a hand-made group",
        "",
        "Three members who each vote on 10 genre-diverse films and mark the Animation / Family / Comedy / Adventure ones "
        "as Interested. Top 5 (IMDb average, number of IMDb votes). This is a first night, so RL v1 and v2 rank the same "
        "way here (no ratings yet for the bandit).",
        "",
        f"| # | {cols} |",
        sep,
    ]
    for i, picks in enumerate(zip(*(sanity[k] for k in MODELS)), 1):
        L.append(f"| {i} | " + " | ".join(picks) + " |")
    L += [
        "",
        "## Interpretation",
        "",
        f"- **Ranking accuracy (NDCG@10):** best is {SHORT[best_ndcg]} ({s[best_ndcg]['ndcg@10']:.3f}). "
        + ", ".join(f"{SHORT[k]} {s[k]['ndcg@10']:.3f}" for k in MODELS) + ".",
        f"- **Reward for the film actually watched:** best is {SHORT[best_reward]} ({s[best_reward]['mean_reward']:.2f}). "
        "First night: " + ", ".join(f"{SHORT[k]} {s[k]['reward_per_session'][0]:.2f}" for k in MODELS) + ".",
        f"- **RL v2 vs v1:** NDCG {v2['ndcg@10'] - v1['ndcg@10']:+.3f}, mean reward {v2['mean_reward'] - v1['mean_reward']:+.2f}, "
        f"learning gain {learning_gain(v1):+.3f} → {learning_gain(v2):+.3f}, p95 latency "
        f"{v1['latency_ms_p95']:.0f} → {v2['latency_ms_p95']:.0f} ms. "
        + ("v2 is better on both ranking and reward."
           if v2["ndcg@10"] > v1["ndcg@10"] and v2["mean_reward"] > v1["mean_reward"]
           else "v2 is not better on both ranking and reward, so v1 should stay deployed; see the tuning runs in MLflow."
           if v2["ndcg@10"] <= v1["ndcg@10"] and v2["mean_reward"] <= v1["mean_reward"]
           else "The result is mixed: v2 wins on one of ranking and reward but not the other."),
        f"- **Speed:** fastest is {SHORT[fastest]} (p95 {s[fastest]['latency_ms_p95']:.0f} ms); all models are far "
        "below the 3 s NFR-01 limit.",
        "- **Mainstream vs obscure:** median IMDb votes of the recommended films — "
        + ", ".join(f"{SHORT[k]} {s[k]['median_imdb_votes_top10']:,}" for k in MODELS) + ". The simulator scores a film's "
        "quality by its raw IMDb average and ignores how many people voted, so a trained model can gain NDCG by "
        "recommending little-known films with a very high average; the RL models' Bayesian rating discounts those on "
        "purpose. A much lower vote count than RL's is a sign a model is exploiting that (see the sanity check).",
        "- **Learning from the group:** only the RL models update from a group's own ratings (per group, isolated). "
        "DL and QML are fixed after training and treat every group with the same function.",
        "- **Data needs:** RL needs no training data. DL and QML need thousands of labelled movie nights; here they come "
        "from the simulator because the IMDb export has no per-user ratings, and they would not exist at launch.",
        "- **What QML adds:** the QML model is hybrid — its six inputs are classical (content fits from the votes and "
        "public ratings) and the 6-qubit circuit learns how to combine them non-linearly with 42 parameters. It runs on an "
        "exact classical simulation of the circuit (checked against Qiskit); at this size there is no quantum speed-up, "
        "and on real quantum hardware every score would need many measurement shots and would carry noise.",
        "- **Caveat:** DL and QML are trained on data from the same simulator they are evaluated on (different seeds), "
        "which favours them; RL v1's weights and RL v2's settings were only grid-searched.",
        "",
        "MLflow: training/tuning runs in experiment `group-recommender-models`; one run per model in "
        "`group-recommender-comparison` (with this report and the JSON attached); registered models "
        + ", ".join(f"`{info[k]['registered_model']}`" for k in MODELS) + ".",
    ]
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(L) + "\n")


def main():
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--groups", type=int, default=sim_mod.N_GROUPS)
    p.add_argument("--sessions", type=int, default=sim_mod.SESSIONS)
    p.add_argument("--seeds", type=int, nargs="+", default=list(sim_mod.EVAL_SEEDS))
    a = p.parse_args()

    mlflow = sim_mod.setup_mlflow(sim_mod.COMPARISON_EXPERIMENT)
    movies, feat = sim_mod.load_features()
    sim = sim_mod.Simulator(movies, feat)

    rankers, info = {}, {}
    for key in MODELS:
        rankers[key], info[key] = load_registered(mlflow, key)
        print(f"loaded {info[key]['registered_model']} v{info[key]['version']}")
    rankers["preference_only"] = RLRanker(feat, use=("compatibility",))
    rankers["rating_only"] = RLRanker(feat, use=("rating",))

    per_seed = []
    for seed in a.seeds:
        print(f"evaluating seed {seed} ...", flush=True)
        per_seed.append(sim_mod.evaluate(rankers, feat, sim, seed, a.groups, a.sessions))
    summary = sim_mod.summarise(per_seed)
    sanity = sanity_example(rankers, feat)
    protocol = {"seeds": a.seeds, "groups": a.groups, "sessions": a.sessions, "catalogue_size": len(movies)}

    for key, r in summary.items():
        with mlflow.start_run(run_name=f"compare-{key}"):
            mlflow.set_tag("family", info[key]["family"] if key in info else "baseline")
            mlflow.log_params({"model": key, **protocol, "seeds": ",".join(map(str, a.seeds)),
                               **({"registered_model": info[key]["registered_model"], "version": info[key]["version"]}
                                  if key in info else {})})
            mlflow.log_metrics({
                "ndcg_at_10": r["ndcg@10"], "precision_at_10": r["precision@10"], "mean_reward": r["mean_reward"],
                "learning_gain": learning_gain(r), "latency_ms_p95": r["latency_ms_p95"],
                "median_imdb_votes_top10": r["median_imdb_votes_top10"],
            })
            for step, v in enumerate(r["reward_per_session"], 1):
                mlflow.log_metric("reward_per_session", v, step=step)

    os.makedirs(os.path.join(sim_mod.ROOT, "docs"), exist_ok=True)
    path_json = os.path.join(sim_mod.ROOT, "docs", "model_comparison.json")
    path_md = os.path.join(sim_mod.ROOT, "docs", "model_comparison.md")
    with open(path_json, "w", encoding="utf-8") as f:
        json.dump({"protocol": protocol, "models": info, "results": summary, "sanity_example": sanity}, f, indent=2)
    write_report(summary, info, sanity, protocol, path_md)
    with mlflow.start_run(run_name="comparison-report"):
        mlflow.log_artifact(path_md)
        mlflow.log_artifact(path_json)

    print(f"\n{'model':16s} {'NDCG@10':>8s} {'P@10':>6s} {'reward':>7s} {'gain':>7s} {'p95 ms':>7s}")
    for key, r in sorted(summary.items(), key=lambda kv: -kv[1]["ndcg@10"]):
        print(f"{key:16s} {r['ndcg@10']:8.4f} {r['precision@10']:6.3f} {r['mean_reward']:7.2f} "
              f"{learning_gain(r):+7.3f} {r['latency_ms_p95']:7.1f}")
    print(f"\nwrote {path_md}")


if __name__ == "__main__":
    main()
